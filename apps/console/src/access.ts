export function operationRequirement(operation: ConsoleOperation): {
  readonly requiredAuthorization: string | undefined;
  readonly requiredRoleAction: OrganizationRoleAction | undefined;
} {
  return {
    requiredAuthorization:
      publicRouteContract(operation).requiredAuthorization ?? ENFORCED_SCOPES[operation],
    requiredRoleAction: operationRoleAction(operation),
  };
}

export function operationAccess(authorization: ConsoleAuthorization): OperationAccess {
  return Object.fromEntries(
    CONSOLE_OPERATIONS.map((operation) => [
      operation,
      canUseRoute(authorization, operationRequirement(operation)),
    ]),
  ) as OperationAccess;
}
