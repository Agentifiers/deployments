import type { ItemType, PlatformRecord } from "../records/index.ts";

type RecordData<Type extends ItemType> = Extract<
  PlatformRecord,
  { readonly itemType: Type }
>["data"];
type ThreadReader<Type extends ItemType> = (
  data: RecordData<Type>,
) => readonly (string | undefined)[];

export type ThreadOwnership<Type extends ItemType> =
  | { readonly kind: "owned"; readonly threads: ThreadReader<Type> }
  | { readonly kind: "erasure-cleanup"; readonly threads: ThreadReader<Type> }
  | { readonly kind: "ingress-route" }
  | { readonly kind: "pseudonymous" }
  | { readonly kind: "retained" };

const INGRESS_ROUTE = { kind: "ingress-route" } as const;
const PSEUDONYMOUS = { kind: "pseudonymous" } as const;
const RETAINED = { kind: "retained" } as const;

const EVENT_AGGREGATES_ERASED_WITH_THREAD = {
  run: "aggregate-owned-by-thread",
  "run-dispatch": "single-event-aggregate",
  thread: "aggregate-owned-by-thread",
} as const satisfies Record<string, "aggregate-owned-by-thread" | "single-event-aggregate">;

const semanticEventThreadIds: ThreadReader<"semantic-event"> = (data) => {
  if (!Object.hasOwn(EVENT_AGGREGATES_ERASED_WITH_THREAD, data.aggregateType)) return [];
  if (data.aggregateType === "thread") return [data.aggregateId];
  return typeof data.payload.threadId === "string" ? [data.payload.threadId] : [];
};

