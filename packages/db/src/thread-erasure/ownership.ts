export function governanceThreadIds(record: PlatformRecord): readonly string[] {
  const ownership = THREAD_OWNERSHIP[record.itemType] as ThreadOwnership<ItemType>;
  if (ownership.kind !== "owned" && ownership.kind !== "erasure-cleanup") return [];
  const threadIds = ownership
    .threads(record.data as RecordData<ItemType>)
    .filter((threadId): threadId is string => typeof threadId === "string" && threadId.length > 0);
  return [...new Set(threadIds)].sort();
}

export function fencedThreadIds(record: PlatformRecord): readonly string[] {
  return THREAD_OWNERSHIP[record.itemType].kind === "owned" ? governanceThreadIds(record) : [];
}
