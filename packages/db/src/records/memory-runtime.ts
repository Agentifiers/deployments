const MemoryShadowSearchInput = Schema.Struct({
  allowedScopeKeys: Schema.optional(StringList),
  memorySpaceIds: Schema.Array(Ulid),
  observability: Schema.optional(ObservabilitySourceContext),
  comparisonPurpose: Schema.optional(Schema.Literals(["quality", "schema-rollout"])),
  placementGeneration: Schema.optional(NonNegativeSafeInteger),
  purpose: Schema.optional(Schema.String),
  query: Schema.String,
  runId: Schema.optional(Ulid),
  searchKeys: Schema.optional(StringList),
  shadow: Schema.Literal(true),
  shadowAttemptId: Ulid,
  shadowOfAttemptId: Ulid,
  strategyOverride: Schema.Literals(["dense-v1", "hybrid-rerank-v1", "hybrid-rrf-v1"]),
  threadId: Schema.optional(Ulid),
  toolCallId: Schema.optional(Ulid),
  topK: Schema.optional(NonNegativeSafeInteger),
  targetId: Schema.optional(Ulid),
});

