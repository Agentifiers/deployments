export interface ReleaseEntryExport {
  readonly name: string;
  readonly typeOnly: boolean;
}

export interface ContractMetadata {
  readonly apiVersion: string;
  readonly codegenSha256: string;
  readonly operationCount: number;
  readonly sha256: string;
}

const REEXPORTS: readonly (ReleaseEntryExport & { readonly from: string })[] = [
  { name: "client", from: "./client.gen.js", typeOnly: false },
  { name: "createClient", from: "./secure-client.js", typeOnly: false },
  { name: "validatePlatformBaseUrl", from: "./transport-security.js", typeOnly: false },
  { name: "createConfig", from: "./client/index.js", typeOnly: false },
  { name: "Client", from: "./client/index.js", typeOnly: true },
];

export const RELEASE_ENTRY_EXPORTS: readonly ReleaseEntryExport[] = [
  ...REEXPORTS,
  { name: "contractMetadata", typeOnly: false },
];

export function releaseEntrySource(contractMetadata: ContractMetadata): string {
  return [
    "// This file is generated by scripts/build-sdk-package.ts.",
    'export * from "./index.js";',
    ...REEXPORTS.map(
      ({ name, from, typeOnly }) => `export ${typeOnly ? "type " : ""}{ ${name} } from "${from}";`,
    ),
    "",
    `export const contractMetadata = ${JSON.stringify(contractMetadata, null, 2)} as const;`,
    "",
  ].join("\n");
}
