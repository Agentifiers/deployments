import type { PublicApiRouteContract } from "./route-contract.ts";

type BrainRouteInput = Omit<
  PublicApiRouteContract,
  "authentication" | "errors" | "idempotency" | "scopeHeaders" | "tag"
>;

const brainErrors = [400, 401, 403, 404, 409, 413, 429, 500, 502, 503, 504] as const;

function brainRoute<const Contract extends BrainRouteInput>(
  contract: Contract,
): PublicApiRouteContract & Contract {
  return {
    authentication: "tenant-jwt",
    errors: brainErrors,
    idempotency: contract.method === "GET" ? "none" : "required",
    scopeHeaders: "organization",
    tag: "Brains",
    ...contract,
  };
}

function brainQueryRoute<const Contract extends BrainRouteInput>(contract: Contract) {
  return { ...brainRoute(contract), scopeHeaders: "tenant" as const };
}

