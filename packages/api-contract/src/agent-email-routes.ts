import { PUBLIC_ID_PATTERN_SOURCE } from "./primitives.ts";
import type { PublicApiRouteContract } from "./route-contract.ts";

type AgentEmailRouteInput = Omit<
  PublicApiRouteContract,
  "authentication" | "errors" | "scopeHeaders" | "tag"
>;

const agentEmailErrors = [400, 401, 403, 404, 409, 422, 429, 500, 502, 503, 504] as const;

function agentEmailRoute<const Contract extends AgentEmailRouteInput>(
  contract: Contract,
  errors: PublicApiRouteContract["errors"] = agentEmailErrors,
): PublicApiRouteContract & Contract {
  return {
    authentication: "platform-bearer",
    errors,
    scopeHeaders: "environment",
    tag: "Agent Email",
    ...contract,
  };
}

